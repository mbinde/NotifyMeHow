import Cocoa

/// Criteria for matching a notification
struct NotificationMatchCriteria: Codable {
    var appName: String = ""          // Empty = match any app
    var keywords: String = ""         // Comma-separated keywords to search in title/subtitle/body
    var matchAll: Bool = false        // true = all keywords must match, false = any keyword matches

    // Legacy fields for migration (kept for decoding old data)
    var titleContains: String = ""
    var bodyContains: String = ""

    /// Check if criteria match the notification content
    func matches(_ content: NotificationContent) -> Bool {
        // App name must match if specified
        if !appName.isEmpty {
            if !content.appName.localizedCaseInsensitiveContains(appName) {
                return false
            }
        }

        // Parse keywords (comma-separated, trimmed)
        let keywordList = keywords.split(separator: ",")
            .map { $0.trimmingCharacters(in: .whitespaces) }
            .filter { !$0.isEmpty }

        // Also check legacy fields for migration
        var allKeywords = keywordList
        if !titleContains.isEmpty {
            allKeywords.append(titleContains)
        }
        if !bodyContains.isEmpty {
            allKeywords.append(bodyContains)
        }

        // If no keywords, match everything
        if allKeywords.isEmpty {
            return true
        }

        // Combine all text to search
        let searchText = "\(content.title) \(content.subtitle) \(content.body)"

        if matchAll {
            // All keywords must match
            for keyword in allKeywords {
                if !searchText.localizedCaseInsensitiveContains(keyword) {
                    return false
                }
            }
            return true
        } else {
            // Any keyword matches
            for keyword in allKeywords {
                if searchText.localizedCaseInsensitiveContains(keyword) {
                    return true
                }
            }
            return false
        }
    }

    /// Returns true if all criteria are empty (matches everything)
    var isEmpty: Bool {
        return appName.isEmpty && keywords.isEmpty && titleContains.isEmpty && bodyContains.isEmpty
    }

    /// Auto-generate a descriptive name from criteria
    var autoGeneratedName: String {
        var parts: [String] = []

        if !appName.isEmpty {
            parts.append(appName)
        }

        // Use keywords, or fall back to legacy fields
        if !keywords.isEmpty {
            parts.append(keywords)
        } else {
            if !titleContains.isEmpty {
                parts.append(titleContains)
            }
            if !bodyContains.isEmpty {
                parts.append(bodyContains)
            }
        }

        if parts.isEmpty {
            return "All Notifications"
        }

        // Format: "App: keywords" or just "keywords"
        if !appName.isEmpty && parts.count > 1 {
            let keywordsPart = parts.dropFirst().joined(separator: " ")
            return "\(appName): \(keywordsPart)"
        }

        return parts.joined(separator: " ")
    }
}

/// A notification rule combining match criteria with a style reference
struct NotificationRule: Codable, Identifiable {
    var id: UUID = UUID()
    var name: String = ""  // Empty = auto-generate from criteria
    var criteria: NotificationMatchCriteria = NotificationMatchCriteria()
    var styleId: UUID? = nil  // nil = no custom notification for this rule
    var enabled: Bool = true  // Whether this rule is active

    /// Check if this rule matches the given notification content
    func matches(_ content: NotificationContent) -> Bool {
        return enabled && criteria.matches(content)
    }

    /// Get display name - either custom name or auto-generated from criteria
    var displayName: String {
        if !name.isEmpty {
            return name
        }
        return criteria.autoGeneratedName
    }

    /// Get the style for this rule, if any
    var style: NotificationStyle? {
        guard let styleId = styleId else { return nil }
        return StylesManager.shared.style(withId: styleId)
    }
}

/// Manages notification rules
class RulesManager {
    static let shared = RulesManager()

    private let rulesKey = "notificationRules"
    private let defaultBehaviorKey = "defaultNotificationBehavior"
    private let defaultStyleIdKey = "defaultStyleId"

    private(set) var rules: [NotificationRule] = []

    /// What to do when no rules match
    enum DefaultBehavior: String, Codable {
        case showCustom = "showCustom"      // Show custom notification with default style
        case noCustom = "noCustom"          // Don't show custom notification
    }

    var defaultBehavior: DefaultBehavior {
        get {
            guard let raw = UserDefaults.standard.string(forKey: defaultBehaviorKey),
                  let behavior = DefaultBehavior(rawValue: raw) else {
                return .noCustom
            }
            return behavior
        }
        set {
            UserDefaults.standard.set(newValue.rawValue, forKey: defaultBehaviorKey)
        }
    }

    /// Style to use when no rules match (if defaultBehavior is .showCustom)
    var defaultStyleId: UUID? {
        get {
            guard let str = UserDefaults.standard.string(forKey: defaultStyleIdKey) else { return nil }
            return UUID(uuidString: str)
        }
        set {
            if let id = newValue {
                UserDefaults.standard.set(id.uuidString, forKey: defaultStyleIdKey)
            } else {
                UserDefaults.standard.removeObject(forKey: defaultStyleIdKey)
            }
        }
    }

    private init() {
        loadRules()
    }

    /// Find the first matching rule for the given notification content
    func findMatchingRule(for content: NotificationContent) -> NotificationRule? {
        for rule in rules {
            if rule.matches(content) {
                return rule
            }
        }
        return nil
    }

    /// Count how many rules use a given style (excluding a specific rule)
    func countRulesUsing(styleId: UUID, excluding ruleId: UUID? = nil) -> Int {
        return rules.filter { rule in
            rule.styleId == styleId && rule.id != ruleId
        }.count
    }

    /// Determine the style to use for a notification, or nil if no custom notification should be shown
    func styleFor(content: NotificationContent) -> NotificationStyle? {
        if let rule = findMatchingRule(for: content) {
            // Rule matched - use its style (or nil if no style set)
            return rule.style
        }

        // No rule matched - use default behavior
        switch defaultBehavior {
        case .showCustom:
            if let styleId = defaultStyleId {
                return StylesManager.shared.style(withId: styleId)
            }
            // Fall back to first available style
            return StylesManager.shared.styles.first
        case .noCustom:
            return nil
        }
    }

    // MARK: - CRUD Operations

    func addRule(_ rule: NotificationRule) {
        rules.append(rule)
        saveRules()
    }

    func updateRule(_ rule: NotificationRule) {
        if let index = rules.firstIndex(where: { $0.id == rule.id }) {
            rules[index] = rule
            saveRules()
        }
    }

    func deleteRule(at index: Int) {
        guard index >= 0 && index < rules.count else { return }
        rules.remove(at: index)
        saveRules()
    }

    func moveRule(from sourceIndex: Int, to destinationIndex: Int) {
        guard sourceIndex >= 0 && sourceIndex < rules.count,
              destinationIndex >= 0 && destinationIndex < rules.count else { return }
        let rule = rules.remove(at: sourceIndex)
        rules.insert(rule, at: destinationIndex)
        saveRules()
    }

    /// Replace all rules with imported rules (for import functionality)
    func replaceAllRules(_ newRules: [NotificationRule]) {
        rules = newRules
        saveRules()
    }

    // MARK: - Persistence

    private func loadRules() {
        guard let data = UserDefaults.standard.data(forKey: rulesKey) else {
            rules = []
            return
        }

        do {
            rules = try JSONDecoder().decode([NotificationRule].self, from: data)
        } catch {
            print("Failed to decode rules: \(error)")
            rules = []
        }
    }

    private func saveRules() {
        do {
            let data = try JSONEncoder().encode(rules)
            UserDefaults.standard.set(data, forKey: rulesKey)
        } catch {
            print("Failed to encode rules: \(error)")
        }
    }
}
